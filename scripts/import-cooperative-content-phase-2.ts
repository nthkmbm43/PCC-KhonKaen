async function main() {
  const { db } = await import("../src/db");
  const { articles, products, revisions, seoMetadata } = await import("../src/db/schema");
  const insertedArticles: string[] = [];
  const skippedArticles: string[] = [];
  let insertedProduct = false;

  await db.transaction(async (tx) => {
    for (const candidate of articlesToImport) {
      const article = articleDocumentSchema.parse(candidate);
      const [created] = await tx.insert(articles).values({
        slug: article.slug,
        title: article.title,
        category: article.category,
        workflowState: "published",
        data: article,
      }).onConflictDoNothing({ target: articles.slug }).returning();

      if (!created) {
        skippedArticles.push(article.slug);
        continue;
      }

      await tx.insert(revisions).values({
        resourceType: "article",
        resourceId: created.id,
        version: 1,
        data: created,
        createdBy: "system:cooperative-content-phase-2",
      });
      insertedArticles.push(article.slug);
    }

    const [createdProduct] = await tx.insert(products).values(precastBeamProduct)
      .onConflictDoNothing({ target: products.slug })
      .returning();

    if (createdProduct) {
      insertedProduct = true;
      await tx.insert(seoMetadata).values({
        resourceType: "product",
        resourceId: createdProduct.id,
        title: precastBeamProduct.seoTitle,
        description: precastBeamProduct.seoDescription,
        keywords: precastBeamProduct.seoKeywords,
        ogImage: precastBeamProduct.image,
      });
      const latest = await tx.select({ version: revisions.version })
        .from(revisions)
        .where(eq(revisions.resourceId, createdProduct.id))
        .orderBy(desc(revisions.version))
        .limit(1);
      await tx.insert(revisions).values({
        resourceType: "product",
        resourceId: createdProduct.id,
        version: (latest[0]?.version ?? 0) + 1,
        data: createdProduct,
        createdBy: "system:cooperative-content-phase-2",
      });
    }
  });

  console.log(JSON.stringify({ insertedArticles, skippedArticles, insertedProduct }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
