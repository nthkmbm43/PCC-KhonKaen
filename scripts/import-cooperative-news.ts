async function main() {
  const { db } = await import("../src/db");
  const { articles, revisions } = await import("../src/db/schema");
  const inserted: string[] = [];
  const skipped: string[] = [];

  await db.transaction(async (tx) => {
    for (const candidate of companyNews) {
      const article = articleDocumentSchema.parse(candidate);
      const [created] = await tx.insert(articles).values({
        slug: article.slug,
        title: article.title,
        category: article.category,
        workflowState: "published",
        data: article,
      }).onConflictDoNothing({ target: articles.slug }).returning();

      if (!created) {
        skipped.push(article.slug);
        continue;
      }

      await tx.insert(revisions).values({
        resourceType: "article",
        resourceId: created.id,
        version: 1,
        data: created,
        createdBy: "system:cooperative-news-import",
      });
      inserted.push(article.slug);
    }
  });

  console.log(JSON.stringify({ inserted, skipped }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
