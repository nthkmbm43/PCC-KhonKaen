async function nextRevisionVersion(
  tx: Parameters<Parameters<typeof import("../src/db")["db"]["transaction"]>[0]>[0],
  revisions: typeof import("../src/db/schema")["revisions"],
  resourceId: string,
) {
  const latest = await tx
    .select({ version: revisions.version })
    .from(revisions)
    .where(eq(revisions.resourceId, resourceId))
    .orderBy(desc(revisions.version))
    .limit(1);
  return (latest[0]?.version ?? 0) + 1;
}

