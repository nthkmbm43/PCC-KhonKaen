async function main() {
  const { db } = await import("../src/db");
  const { articles, revisions } = await import("../src/db/schema");
  const inserted: string[] = [];
  const skipped: string[] = [];

  await db.transaction(async (tx) => {
    for (const candidate of cooperativeArticles) {
      const article = articleDocumentSchema.parse(candidate);
      const [created] = await tx
        .insert(articles)
        .values({
          slug: article.slug,
          title: article.title,
          category: article.category,
          workflowState: "published",
          data: article,
        })
        .onConflictDoNothing({ target: articles.slug })
        .returning();

      if (!created) {
        skipped.push(article.slug);
        continue;
      }

      const latest = await tx
        .select({ version: revisions.version })
        .from(revisions)
        .where(eq(revisions.resourceId, created.id))
        .orderBy(desc(revisions.version))
        .limit(1);

      await tx.insert(revisions).values({
        resourceType: "article",
        resourceId: created.id,
        version: (latest[0]?.version ?? 0) + 1,
        data: created,
        createdBy: "system:cooperative-content-import",
      });
      inserted.push(article.slug);
    }
  });

  console.log(JSON.stringify({ inserted, skipped }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
