async function main() {
  const { db } = await import("../src/db");
  const { articles, revisions } = await import("../src/db/schema");

  await db.transaction(async (tx) => {
    const [existing] = await tx.select().from(articles).where(eq(articles.slug, slug)).limit(1);
    if (!existing) throw new Error(`Article not found: ${slug}`);

    await tx
      .update(articles)
      .set({
        title: article.title,
        category: article.category,
        workflowState: "published",
        data: article,
        updatedAt: new Date(),
      })
      .where(eq(articles.id, existing.id));

    const latest = await tx
      .select({ version: revisions.version })
      .from(revisions)
      .where(eq(revisions.resourceId, existing.id))
      .orderBy(desc(revisions.version))
      .limit(1);

    await tx.insert(revisions).values({
      resourceType: "article",
      resourceId: existing.id,
      version: (latest[0]?.version ?? 0) + 1,
      data: article,
      createdBy: "system:l-wall-priority-update",
    });
  });

  console.log(JSON.stringify({ updated: slug, title: article.title }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
